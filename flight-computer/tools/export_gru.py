"""Export a seed-42 PSIntelligence run bundle as constexpr FP32 C++ weights."""
import argparse
import hashlib
import json
from pathlib import Path

import joblib
import numpy as np
import torch


FEATURES = ('altitude_noisy_rel', 'velocity_z', 'acceleration_inertial',
            'tilt_angle', 'gyro_roll_noisy', 'dynamic_pressure')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export(bundle):
    config = json.loads((bundle / 'run.json').read_text(encoding='utf-8'))
    if (tuple(config['features']) != FEATURES or config['seed'] != 42 or config['window'] != 100
            or config['hidden_dim'] != 32 or config['num_layers'] != 1 or config['dt'] != .02
            or config['stride'] != 10 or not config.get('train_only_augmentations')):
        raise ValueError('expected augmented seed 42, 100 × 6 features, one GRU layer of 32 units')
    weights, scaler_path = bundle / 'model.pth', bundle / 'scaler.pkl'
    state = torch.load(weights, map_location='cpu', weights_only=True)
    scaler = joblib.load(scaler_path)
    tensors = {
        'kMean': (scaler.mean_, (6,)), 'kScale': (scaler.scale_, (6,)),
        'kInputWeight': (state['gru.weight_ih_l0'], (96, 6)),
        'kHiddenWeight': (state['gru.weight_hh_l0'], (96, 32)),
        'kInputBias': (state['gru.bias_ih_l0'], (96,)),
        'kHiddenBias': (state['gru.bias_hh_l0'], (96,)),
        'kHeadWeight': (state['fc.0.weight'], (64, 32)),
        'kHeadBias': (state['fc.0.bias'], (64,)),
        'kOutputWeight': (state['fc.3.weight'][0], (64,)),
        'kOutputBias': (state['fc.3.bias'], (1,)),
    }
    if not (np.asarray(scaler.scale_) > 0).all():
        raise ValueError('scales must be positive')
    lines = ['#pragma once', '', '// Generated by tools/export_gru.py. Do not edit.',
             f'// model.pth SHA-256: {digest(weights)}', f'// scaler.pkl SHA-256: {digest(scaler_path)}',
             'namespace apogee_gru { namespace weights {', '']
    for name, (data, shape) in tensors.items():
        values = np.asarray(data, dtype=np.float32)
        if values.shape != shape or not np.isfinite(values).all():
            raise ValueError(f'incompatible tensor: {name}')
        flat = [f'{float(value):.8e}f' for value in values.flat]
        lines.append(f'constexpr float {name}[{values.size}] = {{')
        lines.extend('    ' + ', '.join(flat[i:i + 6]) + ',' for i in range(0, len(flat), 6))
        lines.extend(['};', ''])
    lines.extend(['}}  // namespace apogee_gru::weights', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('bundle', type=Path, help='trusted local PSIntelligence checkpoint directory')
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.write_text(export(args.bundle), encoding='utf-8', newline='\n')
